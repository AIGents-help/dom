import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createClient } from '@supabase/supabase-js';
import { chromium } from 'playwright';

const enabled = process.env.E2E_ISOLATED_SUPABASE === 'true';
const base = process.env.E2E_BASE_URL || 'http://127.0.0.1:3000';
const db = process.env.NEXT_PUBLIC_SUPABASE_URL;
const anon = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
const service = process.env.SUPABASE_SERVICE_ROLE_KEY;

test('photo review displays private images and saves decisions and report notes', {skip: !enabled, timeout:180000}, async () => {
  assert.ok(db && anon && service);
  for (const host of [db,base]) assert.match(host, /^https?:\/\/(127\.0\.0\.1|localhost)(:|\/)/, 'use a disposable loopback environment only');
  const admin = createClient(db,service,{auth:{persistSession:false}});
  const stamp = `${Date.now()}-${Math.random().toString(36).slice(2,8)}`;
  const email = `photo-review-${stamp}@e2e.dom.invalid`, password = `Photo-${stamp}!Aa1`;
  const {data:created,error:createError}=await admin.auth.admin.createUser({email,password,email_confirm:true});
  assert.ifError(createError);
  const user=created.user;
  const paths=[];
  let browser, context, contractor, mission, job, project;
  try {
    const seed=async(table,row)=>{
      const {data,error}=await admin.from(table).insert(row).select('*').single();
      assert.ifError(error); return data;
    };
    contractor=await seed('contractors',{user_id:user.id,full_name:'Photo Review Tester',email,status:'active'});
    await seed('dominic_profiles',{user_id:user.id,plan:'organization',status:'active'});
    mission=await seed('mission_requests',{requester_name:'Photo review fixture',requester_email:email,service_type:'aerial_images',location:'Software test only',status:'approved'});
    job=await seed('jobs',{mission_request_id:mission.id,title:'Photo review fixture job',service_type:'aerial_images',location:'Software test only',status:'scheduled'});
    project=await seed('mapping_projects',{job_id:job.id,contractor_id:contractor.id,name:'Photo review workspace',status:'uploaded',image_count:0});
    const asset=await seed('dominic_assets',{user_id:user.id,name:'Photo Review Tank',asset_type:'tank'});
    const inspection=await seed('dominic_inspections',{user_id:user.id,asset_id:asset.id,mapping_project_id:project.id,inspection_type:'visual',status:'review',objective:'Review coating and record supported observations.'});
    const previous=await seed('dominic_inspections',{user_id:user.id,asset_id:asset.id,inspection_type:'visual',status:'complete'});
    // Existing generated demonstration image: not real aircraft or accuracy evidence.
    const bytes=await readFile(new URL('../public/images/dominic-demo/refinery-aerial-v1.webp',import.meta.url));
    const image=async(record,name)=>{
      const path=`${user.id}/dominic-inspections/${record.id}/${name}.webp`;
      const {error}=await admin.storage.from('dominic-inspection-evidence').upload(path,bytes,{contentType:'image/webp'});
      assert.ifError(error); paths.push(path);
      return seed('dominic_inspection_media',{user_id:user.id,asset_id:asset.id,inspection_id:record.id,media_type:'image',sensor_mode:'rgb',storage_path:path,original_filename:`${name}.webp`});
    };
    const current=await image(inspection,'current'), baseline=await image(previous,'previous');
    const finding=await seed('dominic_findings',{user_id:user.id,asset_id:asset.id,inspection_id:inspection.id,finding_type:'corrosion',title:'Coating condition at tank rim',severity:'medium',review_status:'needs_review',description:'Possible coating wear near the rim. Review the photograph before assigning repair.',confidence:0.8,sensor_mode:'rgb',detector:{mediaId:current.id,baselineSourceMediaId:baseline.id,provider:'software-fixture',comparisonNote:'Synthetic example for UI verification only.'},spatial_anchor:{mediaId:current.id,imageRegion:{x:0.2,y:0.2,width:0.2,height:0.2}}});
    const second=await seed('dominic_findings',{user_id:user.id,asset_id:asset.id,inspection_id:inspection.id,finding_type:'visual_anomaly',title:'Second review suggestion',severity:'low',review_status:'needs_review',detector:{mediaId:current.id},spatial_anchor:{}});
    const unlinked=await seed('dominic_findings',{user_id:user.id,asset_id:asset.id,inspection_id:inspection.id,finding_type:'visual_anomaly',title:'Suggestion without a photograph',severity:'low',review_status:'needs_review',detector:{},spatial_anchor:{}});
    const client=createClient(db,anon,{auth:{persistSession:false}});
    const {data:login,error:loginError}=await client.auth.signInWithPassword({email,password});
    assert.ifError(loginError);
    browser=await chromium.launch({headless:true});
    context=await browser.newContext({viewport:{width:1440,height:1000}});
    await context.addInitScript(({key,session})=>localStorage.setItem(key,JSON.stringify(session)),{key:`sb-${new URL(db).hostname.split('.')[0]}-auth-token`,session:login.session});
    const page=await context.newPage(); page.setDefaultTimeout(15000);
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`${base}/dominic`,{waitUntil:'domcontentloaded'});
    const consent=page.getByRole('region',{name:'Cookie consent',exact:true});
    await consent.getByRole('button',{name:'Essential Only',exact:true}).click();
    await consent.waitFor({state:'hidden'});
    await page.getByRole('button').filter({hasText:'Photo review workspace'}).click();
    await page.getByRole('button',{name:'Plans & inspections',exact:true}).click();
    await page.getByRole('region',{name:'Project plans and inspections',exact:true}).getByRole('button',{name:'Review inspection of Photo Review Tank',exact:true}).click();
    const workspace=page.getByRole('region',{name:'Intelligent Inspection',exact:true});
    const open=async(title, fromMarker=false)=>{
      // Only localized findings have image markers. The saved-finding queue
      // also opens unlocalized findings and findings without a source image.
      const opener=fromMarker
        ? workspace.getByRole('button',{name:`Open callout ${title}`,exact:true})
        : workspace.getByRole('region',{name:'Finding review queue',exact:true}).getByRole('button',{name:`Review saved finding ${title}`,exact:true});
      await opener.click();
      const dialog=page.getByRole('dialog',{name:title,exact:true});
      await dialog.waitFor(); return dialog;
    };
    const close=async(dialog)=>{await dialog.getByRole('button',{name:'Close callout',exact:true}).click();await dialog.waitFor({state:'hidden'});};
    let dialog=await open(finding.title,true);
    const photo=dialog.getByRole('img',{name:'Current inspection evidence',exact:true});
    await photo.waitFor();
    await page.waitForFunction(()=>[...document.images].some(image=>image.alt==='Current inspection evidence' && image.complete && image.naturalWidth>0));
    await dialog.getByRole('img',{name:'Marked finding area',exact:true}).waitFor();
    await dialog.getByRole('button',{name:'Zoom in',exact:true}).click();
    assert.match(await dialog.getByRole('button',{name:'Fit image',exact:true}).innerText(),/150%/);
    await dialog.getByRole('button',{name:'Fit image',exact:true}).click();
    await dialog.getByRole('button',{name:'Hide marked area',exact:true}).click();
    assert.equal(await dialog.getByRole('img',{name:'Marked finding area',exact:true}).count(),0);
    await dialog.getByRole('button',{name:'Show marked area',exact:true}).click();
    await page.screenshot({path:'/tmp/dom-photo-review-desktop.png'});
    await dialog.getByRole('button',{name:'Overlay previous image',exact:true}).click();
    await dialog.getByRole('slider',{name:'Horizontal alignment',exact:true}).focus();
    await dialog.getByRole('slider',{name:'Horizontal alignment',exact:true}).press('ArrowRight');
    assert.equal(await dialog.getByRole('slider',{name:'Horizontal alignment',exact:true}).inputValue(),'1');
    await dialog.getByRole('button',{name:'Reset alignment',exact:true}).click();
    assert.equal(await dialog.getByRole('slider',{name:'Horizontal alignment',exact:true}).inputValue(),'0');
    await dialog.getByRole('button',{name:'Show images separately',exact:true}).click();
    const note=dialog.getByRole('textbox',{name:'Note for report',exact:true});
    await note.fill('Inspect the rim at closer range before assigning repair.');
    assert.equal(await dialog.getByRole('button',{name:'Confirm issue',exact:true}).isDisabled(),true);
    assert.equal(await dialog.getByRole('link',{name:'Preview inspection report',exact:true}).count(),0);
    await page.keyboard.press('Escape');
    await dialog.getByRole('region',{name:'Unsaved report note',exact:true}).waitFor();
    await dialog.getByRole('button',{name:'Keep editing',exact:true}).click();
    const noteUrl=`${base}/api/dominic/findings/${finding.id}/report-note`;
    await page.route(noteUrl,route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Test interrupted save'})}),{times:1});
    await dialog.getByRole('button',{name:'Save report note',exact:true}).click();
    await dialog.getByRole('alert').filter({hasText:'Test interrupted save'}).waitFor();
    assert.equal(await note.inputValue(),'Inspect the rim at closer range before assigning repair.');
    await dialog.getByRole('button',{name:'Save report note',exact:true}).click();
    await dialog.getByRole('status').filter({hasText:'Report note saved.'}).waitFor();
    const saved=await admin.from('dominic_findings').select('detector').eq('id',finding.id).single();
    assert.ifError(saved.error); assert.equal(saved.data.detector.reportNote,'Inspect the rim at closer range before assigning repair.');
    assert.equal(saved.data.detector.mediaId,current.id);
    await close(dialog); dialog=await open(finding.title);
    await dialog.getByRole('button',{name:'Save report note',exact:true}).waitFor();
    await page.waitForFunction(()=>document.querySelector('[aria-label="Note for report"]')?.value==='Inspect the rim at closer range before assigning repair.');
    await dialog.getByRole('button',{name:'Confirm issue',exact:true}).click();
    await dialog.getByRole('status').filter({hasText:'Finding confirmed.'}).waitFor();
    const confirmed=await admin.from('dominic_findings').select('review_status').eq('id',finding.id).single();
    assert.ifError(confirmed.error); assert.equal(confirmed.data.review_status,'confirmed');
    const linked=await admin.from('dominic_issue_findings').select('issue_id').eq('finding_id',finding.id);
    assert.ifError(linked.error); assert.equal(linked.data.length,1);
    assert.equal(await dialog.getByRole('button',{name:'Confirm issue',exact:true}).count(),0);
    const [reportPage]=await Promise.all([context.waitForEvent('page'),dialog.getByRole('link',{name:'Preview inspection report',exact:true}).click()]);
    await reportPage.getByText('Inspect the rim at closer range before assigning repair.',{exact:false}).waitFor();
    await reportPage.close();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/dom-photo-review-phone.png'});
    assert.ok(await dialog.evaluate(element=>element.scrollWidth<=element.clientWidth+1),'dialog has no horizontal overflow');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'page fits phone');
    await dialog.getByRole('textbox',{name:'Note for report',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:'/tmp/dom-photo-review-phone-actions.png'});
    await close(dialog);
    await page.setViewportSize({width:1440,height:1000});
    assert.equal(await workspace.getByRole('button',{name:`Open callout ${second.title}`,exact:true}).count(),0,'Do not invent a marker for an unlocalized finding');
    dialog=await open(second.title);
    await dialog.getByRole('button',{name:'Dismiss',exact:true}).click();
    await dialog.getByRole('status').filter({hasText:'Finding dismissed.'}).waitFor();
    const dismissed=await admin.from('dominic_findings').select('review_status').eq('id',second.id).single();
    assert.ifError(dismissed.error); assert.equal(dismissed.data.review_status,'dismissed');
    await dialog.getByRole('textbox',{name:'Note for report',exact:true}).fill('Discard this local edit.');
    await dialog.getByRole('button',{name:'Close callout',exact:true}).click();
    await dialog.getByRole('button',{name:'Discard unsaved note',exact:true}).click();
    await dialog.waitFor({state:'hidden'});
    assert.equal(await workspace.getByRole('button',{name:`Open callout ${unlinked.title}`,exact:true}).count(),0,'A finding without a photo must still open through the queue');
    dialog=await open(unlinked.title);
    await dialog.getByRole('heading',{name:'No linked photograph',exact:true}).waitFor();
    assert.equal(await dialog.getByRole('button',{name:'Confirm issue',exact:true}).isDisabled(),true);
    await close(dialog);
    const evidenceUrl=`${base}/api/dominic/inspections/${inspection.id}/report?findingId=${unlinked.id}`;
    await page.route(evidenceUrl,route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({inspection:{id:'wrong-inspection'},findings:[],media:[],baselineMedia:[]})}),{times:1});
    dialog=await open(unlinked.title);
    await dialog.getByRole('alert').filter({hasText:'did not match'}).waitFor();
    assert.equal(await dialog.getByRole('img',{name:'Current inspection evidence',exact:true}).count(),0);
    assert.equal(await dialog.getByRole('button',{name:'Save report note',exact:true}).isDisabled(),true);
    await close(dialog);
    assert.deepEqual(errors,[]);
  } finally {
    await context?.close(); await browser?.close();
    if(paths.length) await admin.storage.from('dominic-inspection-evidence').remove(paths);
    await admin.from('dominic_issue_events').delete().eq('user_id',user.id);
    await admin.from('dominic_issue_findings').delete().eq('user_id',user.id);
    await admin.from('dominic_issues').delete().eq('user_id',user.id);
    await admin.from('dominic_findings').delete().eq('user_id',user.id);
    await admin.from('dominic_inspection_media').delete().eq('user_id',user.id);
    await admin.from('dominic_inspections').delete().eq('user_id',user.id);
    await admin.from('dominic_assets').delete().eq('user_id',user.id);
    if(project) await admin.from('mapping_projects').delete().eq('id',project.id);
    if(job) await admin.from('jobs').delete().eq('id',job.id);
    if(mission) await admin.from('mission_requests').delete().eq('id',mission.id);
    if(contractor) await admin.from('contractors').delete().eq('id',contractor.id);
    await admin.auth.admin.deleteUser(user.id);
  }
});